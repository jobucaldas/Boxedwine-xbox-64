#!/usr/bin/env python3
"""B61: bake DejaVu Sans Mono (Bitstream Vera/DejaVu licence, free to embed) ASCII 32..126
into an 8-bit coverage atlas header for the on-screen log view (logview.inc)."""
from PIL import Image, ImageDraw, ImageFont
import sys
SIZE, W, H = 17, 10, 20
f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf', SIZE)
asc, _ = f.getmetrics()
out = ['/* generated by linux/gen-logfont.py: DejaVu Sans Mono %dpx, cell %dx%d, ASCII 32..126 */' % (SIZE, W, H),
       '#define LOGFONT_W %d' % W, '#define LOGFONT_H %d' % H,
       'static const unsigned char logfont[95][%d] = {' % (W * H)]
for c in range(32, 127):
    im = Image.new('L', (W, H), 0)
    ImageDraw.Draw(im).text((0, H - 4 - asc), chr(c), font=f, fill=255)
    px = list(im.getdata())
    out.append(' {' + ','.join(str(p) for p in px) + '},')
out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
