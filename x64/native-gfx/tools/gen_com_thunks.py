#!/usr/bin/env python3
"""Generate typed in-process COM boundary stubs from MinGW C vtables.

C declarations supply ABI types/slot order. The small array policy below supplies
COM direction/count semantics absent from these declarations. Unknown patterns
abort generation rather than silently passing wrapper addresses to the driver.
"""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
HEADERS = ('unknwn.h', 'd3d11.h', 'd3d11_1.h', 'dxgi.h', 'dxgi1_2.h')
REQUIRED = ('ID3D11Device', 'ID3D11Device1', 'ID3D11DeviceContext',
            'ID3D11DeviceContext1', 'IDXGIFactory', 'IDXGIFactory1',
            'IDXGIFactory2', 'IDXGIAdapter', 'IDXGIAdapter1',
            'IDXGISwapChain', 'IDXGISwapChain1', 'IDXGIDevice')
BANNER = '/* Generated by tools/gen_com_thunks.py; do not edit. */\n'


def parse(include):
    interfaces = {}
    for filename in HEADERS:
        source = (include / filename).read_text()
        for iface, body in re.findall(r'typedef struct (\w+)Vtbl\s*\{(.*?)END_INTERFACE', source, re.S):
            if filename == "unknwn.h" and iface != "IUnknown":
                continue
            methods = []
            for ret, name, args in re.findall(r'(\w+)\s*\(STDMETHODCALLTYPE \*(\w+)\)\((.*?)\);', body, re.S):
                params = []
                for arg in args.split(','):
                    arg = ' '.join(arg.split())
                    # C array parameters decay to pointers, also inside packets.
                    arg = re.sub(r'(\w+)\[[^]]*\]$', r'*\1', arg)
                    match = re.fullmatch(r'(.*?)\b(\w+)', arg)
                    if not match:
                        raise ValueError(arg)
                    params.append((match[1].strip(), match[2]))
                methods.append((ret, name, params))
            assert len(methods) == body.count('STDMETHODCALLTYPE *'), iface
            interfaces[iface] = methods
    assert all(i in interfaces for i in REQUIRED)
    # Generate the requested surface and its typed interface dependencies only.
    selected = set(REQUIRED) | {'IUnknown'}
    while True:
        extra = {token for iface in selected for _, _, params in interfaces[iface]
                 for typ, _ in params for token in re.findall(r'\bI\w+\b', typ)
                 if token in interfaces}
        if extra <= selected:
            break
        selected |= extra
    return {i: m for i, m in interfaces.items() if i in selected}


def array_count(method, name, params):
    """Explicit semantic policy for COM interface arrays (not scalar outputs)."""
    names = {n: t for t, n in params}
    candidates = {'ppConstantBuffers': 'NumBuffers', 'ppVertexBuffers': 'NumBuffers',
                  'ppSOTargets': 'NumBuffers', 'ppShaderResourceViews': 'NumViews',
                  'ppSamplers': 'NumSamplers', 'ppUnorderedAccessViews': 'NumUAVs',
                  'ppRenderTargetViews': 'NumRTVs' if 'NumRTVs' in names else 'NumViews',
                  'ppClassInstances': 'NumClassInstances' if 'NumClassInstances' in names else 'pNumClassInstances',
                  'ppResources': 'NumResources', 'resources': 'resource_count', 'surface': 'surface_count'}
    count = candidates.get(name)
    if count and count in names:
        return f'(*p->{count})' if '*' in names[count] else f'p->{count}'
    return None


def generate(interfaces):
    packets = [BANNER, '#ifndef D3DPASS_PACKETS_H\n#define D3DPASS_PACKETS_H\n']
    guest = [BANNER, '#include "../d3dpass/runtime.h"\n']
    host = [BANNER, '#include "../d3dpass/runtime.h"\n']
    tables = []
    index = 0
    for iface, methods in interfaces.items():
        guest.append(f'static const {iface}Vtbl vt_{iface};\n')
    for iface, methods in interfaces.items():
        slots = []
        for ret, method, params in methods:
            ident = f'{iface}_{method}'
            packets.append(f'struct args_{ident} {{\n')
            packets.extend(f'    {t} {n};\n' for t, n in params)
            if ret != 'void':
                packets.append(f'    {ret} result;\n')
            packets.append('};\n')
            signature = ', '.join(f'{t} {n}' for t, n in params)
            guest.append(f'static {ret} STDMETHODCALLTYPE guest_{ident}({signature})\n{{\n')
            guest.append(f'    struct args_{ident} p = {{' + ', '.join(f'.{n}={n}' for t, n in params) + '};\n')
            guest.append(f'    NTSTATUS thunk_status=d3dpass_generated_call({index}, &p);\n')
            if ret == 'HRESULT':
                guest.append('    if(thunk_status) return E_FAIL;\n')
            else:
                guest.append('    (void)thunk_status;\n')
            if method in ('AddRef', 'Release'):
                delta = 1 if method == 'AddRef' else -1
                guest.append(f'    return d3dpass_reference(This,{delta});\n')
            elif ret != 'void':
                guest.append('    return p.result;\n')
            guest.append('}\n')
            slots.append(f'    .{method}=guest_{ident},\n')
            host.append(f'static NTSTATUS host_{ident}(void *arg)\n{{\n    struct args_{ident} *p=arg;\n')
            callargs, before, after = [], [], []
            for typ, name in params:
                it = re.search(r'\b(I\w+)\b', typ)
                if not it or '*' not in typ:
                    callargs.append('p->' + name)
                    continue
                target = it[1]
                if typ.count('*') == 1:
                    callargs.append(f'({typ})d3dpass_unwrap(p->{name})')
                    continue
                count = array_count(method, name, params)
                is_input = 'const' in typ or method == 'QueryResourceResidency'
                if is_input:
                    assert count, (iface, method, typ, name)
                # Interface output arrays need temporaries: host pointers must
                # never be observable in guest storage, even on failed calls.
                size = count or '1'
                before += [f'    UINT n_{name}=p->{name} ? (UINT)({size}) : 0;\n',
                           f'    if(n_{name}>4096) return d3dpass_marshal_error();\n',
                           f'    {target} *a_{name}[n_{name} ? n_{name} : 1];\n',
                           f'    for(UINT j=0;j<n_{name};++j) a_{name}[j]=' +
                           (f'({target} *)d3dpass_unwrap(p->{name}[j]);\n' if is_input else 'NULL;\n')]
                if not is_input:
                    before.append(f'    for(UINT j=0;j<n_{name};++j) p->{name}[j]=NULL;\n')
                callargs.append(f'p->{name} ? a_{name} : NULL')
                if not is_input:
                    # GetShader can reduce the in/out class-instance count.
                    limit = f'n_{name}'
                    if count and '(*p->' in count:
                        limit = f'(n_{name} < (UINT){count} ? n_{name} : (UINT){count})'
                    after.append(f'    for(UINT j=0;j<{limit};++j) p->{name}[j]=({target} *)d3dpass_wrap_iid((uintptr_t)a_{name}[j], &IID_{target});\n')
            # IID-directed void** outputs (QI/GetParent/GetBuffer/OpenSharedResource).
            iid = next((n for t, n in params if t == 'REFIID'), None)
            if iid:
                for k, (typ, name) in enumerate(params):
                    if typ.replace(' ', '') == 'void**':
                        before.append(f'    void *a_{name}=NULL;\n')
                        before.append(f'    if(p->{name}) *p->{name}=NULL;\n')
                        before.append(f'    if(!d3dpass_vtable(p->{iid})) {{ p->result=E_NOINTERFACE; return 0; }}\n')
                        callargs[k] = f'p->{name} ? &a_{name} : NULL'
                        after.append(f'    if(p->{name}) *p->{name}=d3dpass_wrap_iid((uintptr_t)a_{name}, p->{iid});\n')
            host.extend(before)
            call = f'(({iface} *)d3dpass_unwrap(p->This))->lpVtbl->{method}(' + ', '.join(callargs) + ')'
            host.append('    ' + ('p->result=' if ret != 'void' else '') + call + ';\n')
            if ret == 'HRESULT' and after:
                host.append('    if(FAILED(p->result)) return 0;\n')
            host.extend(after)
            if ret == 'HRESULT' and after:
                host.append('    if(d3dpass_take_wrap_error()) p->result=E_OUTOFMEMORY;\n')
            host.append('    return 0;\n}\n')
            tables.append(f'    host_{ident},\n')
            index += 1
        guest.append(f'static const {iface}Vtbl vt_{iface} = {{\n' + ''.join(slots) + '};\n')
        guest.append(f'_Static_assert(sizeof({iface}Vtbl)=={len(methods)}*sizeof(void *), "{iface} header slot count");\n')
    guest.append('const void *d3dpass_vtable(REFIID iid)\n{\n')
    for iface in interfaces:
        guest.append(f'    if(IsEqualGUID(iid,&IID_{iface})) return &vt_{iface};\n')
    guest.append('    return NULL;\n}\n')
    host.append('static const d3dpass_entry_t generated_table[] = {\n' + ''.join(tables) + '};\n')
    host.append('NTSTATUS d3dpass_host_generated(void *arg)\n{\n    struct generated_params *p=arg;\n    if(p->method>=sizeof(generated_table)/sizeof(*generated_table)) return (NTSTATUS)0xc000000d;\n    return generated_table[p->method](p->args);\n}\n')
    packets.append('#endif\n')
    return {'packets.h': ''.join(packets), 'guest.c': ''.join(guest), 'host.c': ''.join(host)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--include', type=pathlib.Path, default=pathlib.Path('/usr/x86_64-w64-mingw32/include'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    interfaces = parse(args.include)
    output = generate(interfaces)
    dest = ROOT / 'generated'
    dest.mkdir(exist_ok=True)
    for filename, content in output.items():
        path = dest / filename
        if args.check:
            assert path.read_text() == content, f'{path}: stale generated output; run make gen'
        else:
            path.write_text(content)
    if args.check:
        actual = (dest / 'guest.c').read_text()
        for iface in REQUIRED:
            body = re.search(r'static const ' + iface + r'Vtbl vt_' + iface + r' = \{(.*?)\};', actual, re.S)[1]
            slots = re.findall(r'\.(\w+)=guest_', body)
            expected = [m[1] for m in interfaces[iface]]
            assert slots == expected, iface
            print(f'COUNT {iface} generated={len(slots)} header={len(expected)} PASS')
        print(f'GENERATED {len(interfaces)} interfaces; all files reproducible PASS')


if __name__ == '__main__':
    main()
